'''
Создание саммари
'''
from pydantic import BaseModel, Field
from back.ai import AI

class SummaryResult(BaseModel):
    description: str = Field(
        description="Краткое описание сценария: зачем пользователи обращаются к агенту с такими запросами."
    )
    typical_phrases: list[str] = Field(
        description="Список из 2-3 типичных формулировок или ключевых слов, которые часто встречаются в запросах."
    )
    pain_points: list[str] = Field(
        description="Список болей или проблем, которые пытаются решить пользователи. Если явных проблем нет, вернуть пустой список."
    )
    broken_queries: list[str] = Field(
        description="Список непонятных, неполных или 'сломанных' запросов из предложенных, где ИИ-агенту будет трудно дать точный ответ."
    )

def summarize_cluster(ai_client: AI, use_case_name: str, cluster_queries: list[str]) -> SummaryResult:
    """
    Создает глубокое саммари по кластеру запросов: вытаскивает боли, паттерны и кривые формулировки.
    """
    queries_text = "\n".join([f"- {q}" for q in cluster_queries])

    system_prompt = f"""
    Ты — продуктовый аналитик ИИ-платформы. Твоя задача — проанализировать кластер логов.
    Ты анализируешь СЫРЫЕ ЛОГИ (ТЕКСТОВЫЕ ЗАПРОСЫ СОТРУДНИКОВ К ИИ-АГЕНТУ).
    ЭТО НЕ СЕРВЕРНЫЕ ЛОГИ. Это то, что сотрудники пишут корпоративному ассистенту в чате (например: "сделай саммари писем", "собери инфо по клиенту из CRM", "найди свободное время в календаре").

    Запрещено писать про: ELK, Prometheus, HTTP-ошибки, падения серверов, DevOps и системное администрирование.
    Пиши исключительно про: автоматизацию рабочих процессов сотрудников, интеграции с бизнес-системами (CRM, Jira, ИСУП, почта, календари) и улучшение пользовательского опыта (UX).
    Название сценария (use-case) для этого кластера: "{use_case_name}".

    Изучи запросы и выдели:
    1. Зачем пользователи это просят (описание).
    2. Какие типовые фразы они используют.
    3. Какие у них "боли" (что им мешает или чего не хватает в процессах).
    4. Есть ли среди запросов "сломанные" (плохо сформулированные, неясные), из-за которых ИИ может ошибиться.
    """

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": f"Сгруппированные запросы:\n{queries_text}"}
    ]

    return ai_client.ask_parsed(
        messages=messages,
        response_model=SummaryResult,
        temperature=0.1
    )
